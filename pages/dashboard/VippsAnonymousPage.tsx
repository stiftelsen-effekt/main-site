import { groq } from "next-sanity";
import Head from "next/head";
import "react-toastify/dist/ReactToastify.css";
import { linksContentQuery } from "../../_queries";
import { PageContent } from "../../components/profile/layout/PageContent/PageContent";
import { MainHeader } from "../../components/shared/layout/Header/Header";
import { getClient } from "../../lib/sanity.client";
import styles from "../../styles/Agreements.module.css";
import { withStaticProps } from "../../util/withStaticProps";
import { GeneralPageProps, LayoutType, getAppStaticProps } from "../_app.page";
import { Navbar } from "../../components/shared/components/Navbar/Navbar";
import { token } from "../../token";
import { ConsentState } from "../../proxy.page";

export const VippsAnonymousPage = withStaticProps(
  async ({
    draftMode = false,
    consentState,
  }: {
    draftMode: boolean;
    consentState: ConsentState;
  }) => {
    const appStaticProps = await getAppStaticProps({
      draftMode,
      consentState,
      layout: LayoutType.Profile,
    });
    const result = await getClient(
      draftMode ? token : undefined,
    ).fetch<FetchVippsAnonymousPageResult>(fetchVippsAnonymousPage);

    return {
      appStaticProps,
      draftMode,
      preview: draftMode,
      token: draftMode ? (token ?? null) : null,
      navbarData: await Navbar.getStaticProps({ dashboard: true, draftMode }),
      data: {
        result: result,
        query: fetchVippsAnonymousPage,
        queryParams: {},
      },
    } satisfies GeneralPageProps;
  },
)(({ data, navbarData, draftMode }) => {
  const page = data.result.vipps?.[0].anonymous_page;

  if (!page) {
    return <div>404{draftMode ? " - Attempting to load preview" : null}</div>;
  }

  return (
    <>
      <Head>
        <title>{data.result.settings[0].title} | Anonym Vipps-avtale</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <MainHeader hideOnScroll={false}>
        <Navbar {...navbarData} />
      </MainHeader>

      <PageContent>
        <h3 className={styles.header}>Anonym Vipps-avtale</h3>
        <div className={styles.infoSection}>
          <p>Du kan stoppe avtalen din når som helst under betalingsavtaler i Vipps-appen.</p>
          <p>
            Ønsker du å endre beløp, trekkdag eller fordeling, kan du kontakte oss på{" "}
            <a href="mailto:donasjon@gieffektivt.no">donasjon@gieffektivt.no</a>, så hjelper vi deg.
          </p>
        </div>
      </PageContent>
    </>
  );
});

type FetchVippsAnonymousPageResult = {
  settings: Array<{
    title?: string;
  }>;
  dashboard: Array<{ dashboard_slug?: { current?: string } }>;
  vipps?: Array<{
    anonymous_page: Record<string, any> & {
      slug: {
        current: string;
      };
    };
  }>;
};

const fetchVippsAnonymousPage = groq`
{
  "settings": *[_type == "site_settings"] {
    title,
  },
  "dashboard": *[_id == "dashboard"] {
    dashboard_slug {
      current
    },
  },
  "vipps": *[_id == "vipps"] {
    anonymous_page->{
      slug {
        current
      },
      header {
        ...,
        seoImage{
          asset->
        },
        ${linksContentQuery}
      },
      content,
    }
  }
}
`;
